"""Render per-hunt results.md, the program report and JSON findings.

Everything here is deterministic: the same dataset produces byte-identical
Markdown and JSON (no wall-clock timestamps), so tests can assert the committed
examples are current.
"""

from __future__ import annotations

import datetime as dt
import json
import math
import os
from typing import Dict, List, Optional

import yaml

from . import data, detections, metrics
from .hunts import ORDER, Finding, get


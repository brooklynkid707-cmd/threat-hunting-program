def _fmt_epoch(epoch: Optional[float]) -> str:
    if epoch is None:
        return "-"
    return dt.datetime.fromtimestamp(epoch, tz=dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def _md_escape(text: str) -> str:
    return str(text).replace("|", "\\|")


def _evidence_brief(hunt_id: str, f: Finding) -> str:
    e = f.evidence
    if hunt_id == "H01":
        return (f"{e['connections']} conns, median {e['median_interval_s']:.0f}s, CV {e['interval_cv']:.2f}, "
                f"robust CV {e['robust_cv']:.2f}, in-band {e['in_band_fraction']:.0%}, bytes CV {e['bytes_out_cv']:.2f}")
    if hunt_id == "H02":
        return f"{e['host_count']} host(s), {e['events']} event(s); e.g. `{e['example_cmdline'][:70]}`"
    if hunt_id == "H03":
        return f"{e['peak_distinct_rc4_spns']} distinct RC4 SPNs in {e['burst_span_s']:.0f}s; {e['rc4_tgs_total']} RC4 TGS total"
    if hunt_id == "H04":
        return f"`{e['cmdline'][:80]}`"
    if hunt_id == "H05":
        return (f"{e['unique_subdomains']} unique subdomains, len {e['mean_label_length']:.1f}, "
                f"entropy {e['mean_entropy_bits']:.2f}, TXT {e['txt_queries']}")
    if hunt_id == "H06":
        return f"{e['host_count']} host(s), `{e['image_path']}`, first seen {e['first_seen']}"
    if hunt_id == "H07":
        a = e["anomaly"]
        return (f"type {a['logon_type']} at {a['hour']:02d}:00 on {a['host']} from {a['src_ip']}; "
                f"interactive = {e['interactive_fraction']:.1%} of {e['total_logons']} logons")
    if hunt_id == "H08":
        return (f"{e['archive_size']/1e6:.0f} MB archive -> {max(e['external_bytes'], e['internal_bytes'])/1e6:.0f} MB to "
                f"{'external' if e['external'] else 'internal'} `{e['destination']}`")
    return ""


def proof_for(hunt_id: str, ds, benign_ds, gt) -> Optional[dict]:
    det_id = get(hunt_id).META.get("detection")
    if not det_id:
        return None
    for rule in detections.load_rules():
        if rule.get("id") == det_id:
            return metrics.detection_proof(rule, ds, benign_ds, gt)
    return None


def hunt_results(hunt_id: str, ds, top: int = 10, gt: Optional[dict] = None,
                 benign_ds=None) -> dict:
    """Run one hunt and collect everything its results.md and JSON need."""
    mod = get(hunt_id)
    findings = mod.run(ds, top=top)
    out = {
        "hunt_id": hunt_id,
        "meta": {k: v for k, v in mod.META.items()},
        "findings": [f.to_dict() for f in findings],
        "fp_review": mod.fp_review(ds, findings),
        "_findings": findings,
    }
    if gt is not None:
        out["score"] = metrics.score_hunt(hunt_id, findings, gt).to_dict()
    proof = proof_for(hunt_id, ds, benign_ds, gt) if gt is not None else None
    if proof:
        out["detection_proof"] = proof
    return out


def render_results_md(res: dict, top: int = 10) -> str:
    hid = res["hunt_id"]
    meta = res["meta"]
    findings: List[Finding] = res["_findings"]
    lines = [
        f"# {hid} results - {meta['name']}",
        "",
        "> Generated by `python -m hunt report` from the synthetic Northwind Logistics dataset. "
        "Do not edit by hand.",
        "",
        f"- **ATT&CK:** {meta['technique']}",
        f"- **Data sources:** {', '.join(meta['data_sources'])}",
        f"- **Entity ranked:** {meta['entity']}",
        f"- **Decision:** **{meta['decision']}**",
        "",
        "## What was found",
        "",
    ]
    mal = [f for f in findings if f.verdict == "malicious"]
    if mal:
        top_f = mal[0]
        lines.append(f"Top finding: **`{top_f.entity}`** scored **{top_f.score:.1f}** - {top_f.explanation}.")
        if len(mal) > 1:
            lines.append("")
            lines.append(f"{len(mal)} findings received a *malicious* verdict; all concern the same activity:")
            for f in mal[1:]:
                lines.append(f"- `{f.entity}` ({f.score:.1f})")
    else:
        lines.append("No finding reached a malicious verdict.")
    lines += [
        "",
        f"## Top {min(top, len(findings))} ranked outliers",
        "",
        "| # | Entity | Score | Verdict | Evidence |",
        "|---|---|---:|---|---|",
    ]
    for i, f in enumerate(findings[:top], 1):
        lines.append(f"| {i} | `{_md_escape(f.entity)}` | {f.score:.1f} | {f.verdict} | "
                     f"{_md_escape(_evidence_brief(hid, f))} |")
    lines += ["", "## False-positive review", ""]
    for n in res["fp_review"]:
        lines.append(f"- {n}")
    lines += ["", "## Decision", "", f"**{meta['decision']}.** {meta['rationale']}", ""]
    proof = res.get("detection_proof")
    if proof:
        lines += [
            f"Graduated rule: `hunt/detections/rules/` -> `{proof['rule_id']}` ({proof['title']}).",
            "",
            "| Check | Result |",
            "|---|---|",
            f"| Alerts on the hunt dataset | {proof['alerts']} ({proof['events_matched']} events) |",
            f"| Matched events on the compromised entities | {proof['events_on_adversary']} of {proof['events_matched']} |",
            f"| Alerts on the benign-only baseline | {proof['benign_baseline_alerts']} |",
            "",
        ]
    if meta.get("data_gaps"):
        lines += ["## Data gaps logged", ""]
        for g in meta["data_gaps"]:
            lines.append(f"- {g}")
        lines.append("")
    score = res.get("score")
    if score:
        lines += [
            "## Scored against ground truth",
            "",
            f"Planted true positive found: **{'yes' if score['true_positive_found'] else 'no'}**, "
            f"rank of first true positive: **{score['rank_of_first_tp']}**, "
            f"precision of malicious verdicts: **{score['precision_at_malicious']:.2f}**.",
            "",
        ]
    return "\n".join(lines)


def load_backlog() -> dict:
    with open(os.path.join(PROGRAM_DIR, "backlog.yaml"), "r", encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def program_summary(all_results: Dict[str, dict], ds, gt: dict) -> dict:
    executed = list(all_results)
    tps = sum(1 for r in all_results.values() if r["score"]["true_positive_found"])
    created = [h for h, r in all_results.items() if r["meta"]["decision"] == "new detection created"]
    gaps_hunts = [h for h, r in all_results.items() if r["meta"]["decision"] == "data gap found"]
    data_gaps = []
    for h, r in all_results.items():
        for g in r["meta"].get("data_gaps", []):
            data_gaps.append((h, g))
    ttf = {h: metrics.time_to_find(get(h), h, ds, gt) for h in executed}
    dwell = [t["dwell_hours"] for t in ttf.values()]
    found = [t["time_to_find_hours"] for t in ttf.values() if t["time_to_find_hours"] is not None]
    return {
        "hunts_executed": len(executed),
        "true_positives": tps,
        "detections_created": created,
        "data_gap_hunts": gaps_hunts,
        "data_gaps": data_gaps,
        "conversion_rate": len(created) / len(executed) if executed else 0.0,
        "time_to_find": ttf,
        "mean_dwell_hours": math.fsum(dwell) / len(dwell) if dwell else 0.0,
        "mean_time_to_find_hours": math.fsum(found) / len(found) if found else None,
    }


def scoring_table_md(all_results: Dict[str, dict]) -> List[str]:
    lines = [
        "| Hunt | Technique | Top-ranked entity | True positive? | Rank of first TP | Decision |",
        "|---|---|---|---|---:|---|",
    ]
    for h, r in all_results.items():
        s = r["score"]
        lines.append(f"| {h} | {s['technique']} | `{_md_escape(s['top_entity'])}` | "
                     f"{'yes' if s['top_is_tp'] else 'no'} | {s['rank_of_first_tp'] or '-'} | {r['meta']['decision']} |")
    return lines


def render_program_md(all_results: Dict[str, dict], summary: dict, ds, backlog: dict) -> str:
    counts = ds.counts()
    lo, hi = ds.time_range()
    lines = [
        "# Hunt program report - Northwind Logistics, cycle 2026-Q3",
        "",
        "> Generated by `python -m hunt report`. Synthetic data, fictional company. Do not edit by hand.",
        "",
        f"Dataset: {sum(counts.values()):,} events from {_fmt_epoch(lo)} to {_fmt_epoch(hi)} "
        f"({', '.join(f'{k} {v:,}' for k, v in counts.items())}).",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Hunts executed | {summary['hunts_executed']} |",
        f"| Hunts that surfaced a true positive | {summary['true_positives']} of {summary['hunts_executed']} |",
        f"| Detections created | {len(summary['detections_created'])} ({', '.join(summary['detections_created'])}) |",
        f"| Hunt-to-detection conversion rate | {summary['conversion_rate']:.1%} |",
        f"| Hunts closed as data gap | {len(summary['data_gap_hunts'])} ({', '.join(summary['data_gap_hunts']) or '-'}) |",
        f"| Data gaps logged | {len(summary['data_gaps'])} |",
        f"| Mean dwell of planted activity in the 14-day window | {summary['mean_dwell_hours']:.1f} h |",
        f"| Mean time-to-find if each hunt ran daily | "
        f"{summary['mean_time_to_find_hours']:.1f} h |" if summary["mean_time_to_find_hours"] is not None
        else "| Mean time-to-find if each hunt ran daily | - |",
        "",
        "## Per-hunt scoring",
        "",
    ]
    lines += scoring_table_md(all_results)
    lines += [
        "",
        "## Dwell vs time-to-find",
        "",
        "Dwell = end of the dataset minus the first planted event for that hunt (how long the "
        "activity went unhunted in this window). Time-to-find = the first daily replay "
        "(`Dataset.until(midnight)`) where the hunt ranks the true positive #1 with a malicious "
        "verdict, minus that first event.",
        "",
        "| Hunt | First planted activity | Dwell (h) | Found by daily run at | Time-to-find (h) |",
        "|---|---|---:|---|---:|",
    ]
    for h, t in summary["time_to_find"].items():
        lines.append(f"| {h} | {_fmt_epoch(t['first_activity_epoch'])} | {t['dwell_hours']:.1f} | "
                     f"{_fmt_epoch(t['found_epoch'])} | {t['time_to_find_hours'] if t['time_to_find_hours'] is not None else '-'} |")
    lines += ["", "## Detections created (hunt-to-detection loop)", "",
              "| Hunt | Rule | Alerts on hunt data | On adversary | Alerts on benign-only baseline |",
              "|---|---|---:|---:|---:|"]
    for h, r in all_results.items():
        p = r.get("detection_proof")
        if p:
            lines.append(f"| {h} | `{p['rule_id']}` | {p['alerts']} | {p['events_on_adversary']}/{p['events_matched']} | "
                         f"{p['benign_baseline_alerts']} |")
    lines += ["", "Hunts that did not graduate:", ""]
    for h, r in all_results.items():
        if r["meta"]["decision"] != "new detection created":
            lines.append(f"- **{h} - {r['meta']['decision']}.** {r['meta']['rationale']}")
    lines += ["", "## Data gaps", ""]
    for h, g in summary["data_gaps"]:
        lines.append(f"- {h}: {g}")
    for b in backlog["hunts"]:
        if b.get("status") == "blocked-data-gap":
            lines.append(f"- Backlog {b['id']} ({b['technique']}) blocked: {b['data_gap']}")
    lines += [
        "",
        "## Next cycle (from program/backlog.yaml)",
        "",
        "| ID | Title | Technique | Intel | Data | Effort | Priority | Status |",
        "|---|---|---|---:|---:|---:|---:|---|",
    ]
    queued = [b for b in backlog["hunts"] if b["status"] != "executed"]
    queued.sort(key=lambda b: -b["priority"])
    for b in queued:
        lines.append(f"| {b['id']} | {b['title']} | {b['technique']} | {b['threat_intel_relevance']} | "
                     f"{b['data_availability']} | {b['effort']} | {b['priority']} | {b['status']} |")
    lines += [
        "",
        "## Intrusion reconstructed from the hunts",
        "",
        "Ordered by first planted activity, the top finding of each hunt. Seven of the eight sit on "
        "`WKS-0042` / `rbaxter`; H07 is the `svc-backup` credential used for RDP to `SRV-0001` from "
        "an internal address, which ties to the same intrusion only through the timeline and must be "
        "confirmed in the follow-up investigation:",
        "",
    ]
    story = sorted(
        ((t["first_activity_epoch"], h) for h, t in summary["time_to_find"].items()),
    )
    for epoch, h in story:
        r = all_results[h]
        f = r["_findings"][0]
        lines.append(f"{len([1 for e, _ in story if e <= epoch])}. {_fmt_epoch(epoch)} - **{h}** "
                     f"({r['meta']['technique']}): `{f.entity}`")
    lines.append("")
    return "\n".join(lines)


def build_all(ds=None, benign_ds=None, top: int = 10) -> dict:
    ds = ds or data.load()
    gt = data.load_ground_truth(ds.path)
    results = {h: hunt_results(h, ds, top=top, gt=gt, benign_ds=benign_ds) for h in ORDER}
    summary = program_summary(results, ds, gt)
    return {"results": results, "summary": summary, "ds": ds, "gt": gt}


def _strip(res: dict) -> dict:
    return {k: v for k, v in res.items() if not k.startswith("_")}


def write_reports(built: dict, hunts_dir: str = HUNTS_DIR, program_dir: str = PROGRAM_DIR,
                  examples_dir: str = EXAMPLES_DIR) -> List[str]:
    """Write hunts/*/results.md, program/program_report.md and examples/*.json."""
    written = []
    results, summary, ds = built["results"], built["summary"], built["ds"]
    for h, r in results.items():
        folder = os.path.join(hunts_dir, HUNT_FOLDERS[h])
        os.makedirs(folder, exist_ok=True)
        fp = os.path.join(folder, "results.md")
        with open(fp, "w", encoding="utf-8") as fh:
            fh.write(render_results_md(r))
        written.append(fp)
    os.makedirs(program_dir, exist_ok=True)
    fp = os.path.join(program_dir, "program_report.md")
    with open(fp, "w", encoding="utf-8") as fh:
        fh.write(render_program_md(results, summary, ds, load_backlog()))
    written.append(fp)
    os.makedirs(examples_dir, exist_ok=True)
    fp = os.path.join(examples_dir, "findings.json")
    with open(fp, "w", encoding="utf-8") as fh:
        json.dump({h: _strip(r) for h, r in results.items()}, fh, indent=2, sort_keys=True)
        fh.write("\n")
    written.append(fp)
    fp = os.path.join(examples_dir, "scores.json")
    scores = {h: r["score"] for h, r in results.items()}
    prog = {k: v for k, v in summary.items() if k != "time_to_find"}
    prog["time_to_find"] = summary["time_to_find"]
    with open(fp, "w", encoding="utf-8") as fh:
        json.dump({"hunts": scores, "program": prog}, fh, indent=2, sort_keys=True)
        fh.write("\n")
    written.append(fp)
    return written
